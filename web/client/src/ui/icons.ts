export type IconName = keyof typeof ICONS;

/** Satır içi HTML (innerHTML şablonları için): `<span class="ic">…svg…</span>`. */
export function iconHtml(name: IconName, cls = ""): string {
  return `<span class="ic${cls ? ` ${cls}` : ""}" aria-hidden="true">${ICONS[name]}</span>`;
}

/** Simge öğesi; `parent` verilirse sonuna eklenir. */
export function icon(name: IconName, cls = "", parent?: HTMLElement): HTMLSpanElement {
  const s = document.createElement("span");
  s.className = cls ? `ic ${cls}` : "ic";
  s.setAttribute("aria-hidden", "true");
  s.innerHTML = ICONS[name];
  parent?.append(s);
  return s;
}

/** Emoji dizileri (birleşik, ten rengi, varyasyon seçicili). */
const EMOJI = /(?:\p{Extended_Pictographic}|\p{Regional_Indicator})(?:️|[\u{1F3FB}-\u{1F3FF}]|‍(?:\p{Extended_Pictographic}|\p{Regional_Indicator}))*/gu;

/** Emojileri atar: başlık, düğme ve etiketler simgesiz, sade yazılır. */
export function stripEmoji(text: string): string {
  return text.replace(EMOJI, "").replace(/️/g, "").replace(/\s{2,}/g, " ").replace(/\(\s+/g, "(").replace(/\s+\)/g, ")").trim();
}
